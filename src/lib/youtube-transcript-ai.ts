import { YoutubeTranscript } from "youtube-transcript";
import { normalizePastedText } from "./paste";

const BASE = "https://youtube-transcript.ai/transcript";

/** youtube-transcript.ai 응답에서 본문만 추출 */
export function cleanYoutubeTranscriptAi(raw: string): string {
  let t = raw.trim();
  if (!t) return "";

  t = t.replace(
    /\n*Generated by https:\/\/youtube-transcript\.ai[\s\S]*$/i,
    ""
  );

  const body = t.match(/##\s*Transcript\s*\n([\s\S]*)/i);
  if (body?.[1]) t = body[1];

  t = t
    .replace(/^#+\s.*$/gm, "")
    .replace(/^Source video:.*$/gim, "")
    .replace(/^Language:.*$/gim, "")
    .replace(/^Other available languages:.*$/gim, "")
    .replace(/^To request a specific language:.*$/gim, "")
    .replace(/^Interactive version.*$/gim, "")
    .replace(/\[(\d{1,2}:\d{2}(?::\d{2})?)\]/g, " ")
    .replace(/^\d{1,2}:\d{2}(?::\d{2})?\s+/gm, "")
    .replace(/\[[^\]\d]{1,16}\]/g, " ")
    .replace(/[♪♫]+/g, " ")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[ \t]{2,}/g, " ");

  t = dedupeTranscriptRepeats(t);
  return normalizePastedText(t);
}

/**
 * youtube-transcript.ai 자동자막은 같은 큐를 2~3번 이어 붙인다.
 * 3단어 이상은 2회 연속이면 한 번만 남기고,
 * 1~2단어는 3회 이상일 때만 접는다. (「네 네」 같은 말더듬은 유지)
 */
export function dedupeTranscriptRepeats(text: string): string {
  const words = text.split(/\s+/).filter(Boolean);
  if (words.length < 4) return text.trim();

  const out: string[] = [];
  let i = 0;
  while (i < words.length) {
    let matched = false;
    const maxLen = Math.min(24, Math.floor((words.length - i) / 2));
    for (let size = maxLen; size >= 1; size--) {
      const minCopies = size >= 3 ? 2 : 3;
      const chunk = words.slice(i, i + size);
      const chunkKey = chunk.join(" ");
      let copies = 1;
      let end = i + size;
      while (end + size <= words.length) {
        const nextKey = words.slice(end, end + size).join(" ");
        if (nextKey !== chunkKey) break;
        copies += 1;
        end += size;
      }
      if (copies >= minCopies) {
        out.push(...chunk);
        i = end;
        matched = true;
        break;
      }
    }
    if (!matched) {
      out.push(words[i]);
      i++;
    }
  }
  return out.join(" ").replace(/\s+/g, " ").trim();
}

/** 응답 헤더의 현재 언어와 다른 자막 코드 */
export function transcriptTrackMeta(raw: string): {
  lang: string;
  available: string[];
} {
  const langRaw =
    raw
      .match(/^Language:\s*([A-Za-z0-9-]{2,12})/m)?.[1]
      ?.toLowerCase() ?? "";
  // "en (auto-generated)" → en, "a-ko" → a-ko
  const lang = langRaw;
  const others = raw.match(/^Other available languages:\s*(.+)$/im)?.[1] ?? "";
  const fromParen = [
    ...others.matchAll(/\(([A-Za-z]{2,8}(?:-[A-Za-z0-9]+)?)\)/g),
  ].map((m) => m[1].toLowerCase());
  const fromToken = [
    ...others.matchAll(/\b(a-[a-z]{2}|[a-z]{2}(?:-[A-Za-z0-9]+)?)\b/gi),
  ].map((m) => m[1].toLowerCase());
  const available = [...new Set([...fromParen, ...fromToken])];
  return { lang, available };
}

export function isKoreanTrackCode(code: string): boolean {
  const c = code.toLowerCase();
  return (
    c === "ko" ||
    c.startsWith("ko-") ||
    c === "a-ko" ||
    c.startsWith("a-ko")
  );
}

/** 본문에 한글이 충분히 있으면 한국어 자막으로 본다. */
export function looksLikeKoreanText(text: string): boolean {
  const sample = text.slice(0, 2500);
  const hangul = (sample.match(/[\uAC00-\uD7A3]/g) || []).length;
  const latin = (sample.match(/[A-Za-z]/g) || []).length;
  if (hangul < 20) return false;
  return hangul >= latin * 0.35;
}

function looksLikeFailure(text: string, status: number): boolean {
  if (status >= 400) return true;
  if (text.length < 40) return true;
  if (/<!doctype html>|<html[\s>]/i.test(text)) return true;
  // 본문에 error·not found가 있어도 자막이면 실패로 보지 않는다.
  if (/##\s*Transcript/i.test(text)) return false;
  const head = text.slice(0, 400).toLowerCase();
  if (
    /no transcript|transcript (is )?not available|captions? (were )?not|video (is )?unavailable|^not found\b/i.test(
      head
    )
  ) {
    return true;
  }
  return false;
}

/** 인증·한도 오류는 언어를 바꿔 재시도하지 않는다. 재시도마다 일일 횟수가 차감된다. */
class TranscriptRequestError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "TranscriptRequestError";
  }
}

function transcriptAiApiKey(): string {
  return process.env.YOUTUBE_TRANSCRIPT_AI_API_KEY?.trim() ?? "";
}

/** 서버에서 youtube-transcript.ai 자막을 가져온다. 키는 서버 환경 변수만 사용한다. */
export async function fetchYoutubeTranscriptAi(
  videoId: string,
  opts?: { lang?: string; timeoutMs?: number }
): Promise<{ text: string; langTried: string; sourceUrl: string }> {
  const id = videoId.trim();
  if (!/^[a-zA-Z0-9_-]{11}$/.test(id)) {
    throw new Error("유효한 YouTube 영상 ID가 아닙니다.");
  }

  const apiKey = transcriptAiApiKey();
  if (!apiKey) {
    throw new Error(
      "youtube-transcript.ai API 키가 없습니다. .env.local에 YOUTUBE_TRANSCRIPT_AI_API_KEY를 넣고 개발 서버를 다시 시작하세요. 키는 https://youtube-transcript.ai/get-api-key 에서 만듭니다."
    );
  }

  const timeoutMs = opts?.timeoutMs ?? 45_000;
  const preferred = opts?.lang?.trim();
  let lastError = "자막을 가져오지 못했습니다.";

  const pull = async (lang: string) => {
    const sourceUrl = lang
      ? `${BASE}/${id}.txt?lang=${encodeURIComponent(lang)}`
      : `${BASE}/${id}.txt`;
    try {
      const res = await fetch(sourceUrl, {
        method: "GET",
        headers: {
          Accept: "text/plain, text/markdown, */*",
          Authorization: `Bearer ${apiKey}`,
          "User-Agent":
            "Mozilla/5.0 (compatible; YouTubeFactCheck/1.0; +local)",
        },
        signal: AbortSignal.timeout(timeoutMs),
        cache: "no-store",
      });
      const raw = await res.text();
      if (res.status === 401 || /api key required/i.test(raw)) {
        throw new TranscriptRequestError(
          "youtube-transcript.ai API 키가 거부되었습니다(HTTP 401). .env.local의 YOUTUBE_TRANSCRIPT_AI_API_KEY를 확인한 뒤 개발 서버를 다시 시작하세요."
        );
      }
      if (res.status === 429) {
        throw new TranscriptRequestError(
          "youtube-transcript.ai 오늘 호출 한도를 넘었습니다(HTTP 429). 무료 키는 하루 10회이며, 00:00 UTC에 초기화됩니다."
        );
      }
      if (
        res.status === 404 &&
        /video is unavailable|transcript unavailable/i.test(raw)
      ) {
        throw new TranscriptRequestError(
          "이 영상은 youtube-transcript.ai에서 열리지 않습니다(HTTP 404). 유튜브에서 비공개·삭제·지역 제한이거나, 그 서비스가 영상을 읽지 못하는 상태입니다."
        );
      }
      if (looksLikeFailure(raw, res.status)) {
        lastError = `자막 응답이 비어 있거나 오류입니다. (${lang || "default"}, HTTP ${res.status})`;
        return null;
      }
      const text = cleanYoutubeTranscriptAi(raw);
      if (text.length < 80) {
        lastError = "가져온 자막이 너무 짧습니다.";
        return null;
      }
      const meta = transcriptTrackMeta(raw);
      return {
        text,
        raw,
        sourceUrl,
        lang: lang || meta.lang || "default",
        meta,
      };
    } catch (e) {
      if (e instanceof TranscriptRequestError) throw e;
      lastError =
        e instanceof Error ? e.message : "자막 API 요청에 실패했습니다.";
      return null;
    }
  };

  /** 헤더가 ko이거나 본문에 한글이 충분하면 한국어로 채택 */
  function acceptAsKorean(
    picked: NonNullable<Awaited<ReturnType<typeof pull>>>
  ): boolean {
    return (
      isKoreanTrackCode(picked.meta.lang) || looksLikeKoreanText(picked.text)
    );
  }

  // 1) 호출자가 언어를 지정한 경우
  if (preferred) {
    const picked = await pull(preferred);
    if (picked) {
      return {
        text: picked.text,
        langTried: preferred,
        sourceUrl: picked.sourceUrl,
      };
    }
  }

  // 2) 기본 트랙 1회 (할당량 절약). 이미 한글이면 그대로 사용.
  const first = await pull("");
  if (first && acceptAsKorean(first)) {
    return {
      text: first.text,
      langTried: first.lang,
      sourceUrl: first.sourceUrl,
    };
  }

  // 3) 기본이 영문 등이면 한국어 트랙 재시도 (ko / a-ko + 목록에 있는 코드)
  const koCandidates = [
    "ko",
    "a-ko",
    ...(first?.meta.available.filter(isKoreanTrackCode) ?? []),
  ].filter((v, i, arr) => arr.indexOf(v) === i && v !== preferred);

  for (const lang of koCandidates) {
    const ko = await pull(lang);
    if (ko && acceptAsKorean(ko)) {
      return { text: ko.text, langTried: lang, sourceUrl: ko.sourceUrl };
    }
  }

  // 4) 한글을 못 찾으면 기본(영문 등)이라도 반환 — 호출측에서 유튜브 직접 폴백 가능
  if (first) {
    return {
      text: first.text,
      langTried: first.lang,
      sourceUrl: first.sourceUrl,
    };
  }

  // 5) 영어 폴백
  if (preferred !== "en") {
    const en = await pull("en");
    if (en) {
      return { text: en.text, langTried: "en", sourceUrl: en.sourceUrl };
    }
  }

  throw new Error(
    `${lastError} youtube-transcript.ai에서 자막이 없는 영상이거나 일시 오류일 수 있습니다.`
  );
}

function parseCaptionJson3(raw: string): string {
  try {
    const json = JSON.parse(raw) as {
      events?: Array<{ segs?: Array<{ utf8?: string }> }>;
    };
    return (json.events || [])
      .flatMap((e) => e.segs || [])
      .map((s) => s.utf8 || "")
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();
  } catch {
    return raw
      .replace(/<[^>]+>/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  }
}

function normalizeCaptionUrl(baseUrl: string): string {
  let url = baseUrl.replace(/\\u0026/g, "&").replace(/&amp;/g, "&");
  if (!/[?&]fmt=/.test(url)) {
    url += (url.includes("?") ? "&" : "?") + "fmt=json3";
  } else if (!/[?&]fmt=json3/.test(url)) {
    url = url.replace(/([?&]fmt=)[^&]*/i, "$1json3");
  }
  return url;
}

/** watch HTML에서 한국어(자동) 자막 baseUrl 추출 */
async function findKoreanCaptionBaseUrl(
  videoId: string,
  timeoutMs: number
): Promise<string | null> {
  try {
    const res = await fetch(
      `https://www.youtube.com/watch?v=${videoId}&hl=ko`,
      {
        headers: {
          "User-Agent":
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
          "Accept-Language": "ko-KR,ko;q=0.9",
        },
        signal: AbortSignal.timeout(timeoutMs),
        cache: "no-store",
      }
    );
    if (!res.ok) return null;
    const html = await res.text();
    const marker = '"captionTracks":';
    const idx = html.indexOf(marker);
    if (idx < 0) return null;
    const start = idx + marker.length;
    let depth = 0;
    let end = start;
    for (let i = start; i < html.length; i++) {
      const ch = html[i];
      if (ch === "[") depth++;
      if (ch === "]") {
        depth--;
        if (depth === 0) {
          end = i + 1;
          break;
        }
      }
    }
    const tracks = JSON.parse(html.slice(start, end)) as Array<{
      languageCode?: string;
      kind?: string;
      baseUrl?: string;
    }>;
    const ko =
      tracks.find(
        (t) =>
          t.languageCode === "ko" &&
          t.kind === "asr" &&
          typeof t.baseUrl === "string"
      ) ||
      tracks.find(
        (t) =>
          (t.languageCode === "ko" ||
            (t.languageCode || "").startsWith("ko-")) &&
          typeof t.baseUrl === "string"
      );
    return ko?.baseUrl ? normalizeCaptionUrl(ko.baseUrl) : null;
  } catch {
    return null;
  }
}

/**
 * 유튜브 한국어 자동자막을 직접 가져온다.
 * youtube-transcript.ai 기본이 영문(en)인 영상(오빠두 luimFKB9ZD8 등) 대응.
 * 1순위: youtube-transcript 패키지(lang=ko) — 할당량 없음
 * 2순위: watch HTML captionTracks / timedtext
 */
export async function fetchYoutubeKoreanTimedText(
  videoId: string,
  timeoutMs = 15_000
): Promise<{ text: string; langTried: string; sourceUrl: string } | null> {
  const id = videoId.trim();
  if (!/^[a-zA-Z0-9_-]{11}$/.test(id)) return null;

  try {
    const parts = await Promise.race([
      YoutubeTranscript.fetchTranscript(id, { lang: "ko" }),
      new Promise<never>((_, reject) =>
        setTimeout(() => reject(new Error("timeout")), timeoutMs)
      ),
    ]);
    const text = normalizePastedText(
      dedupeTranscriptRepeats(
        parts
          .map((p) => p.text)
          .join(" ")
          .replace(/\s+/g, " ")
          .trim()
      )
    );
    if (text.length >= 80 && looksLikeKoreanText(text)) {
      return {
        text,
        langTried: "ko-youtube",
        sourceUrl: `https://www.youtube.com/watch?v=${id}&lang=ko`,
      };
    }
  } catch {
    /* timedtext 폴백 */
  }

  const fromPlayer = await findKoreanCaptionBaseUrl(id, timeoutMs);
  const attempts = [
    ...(fromPlayer ? [fromPlayer] : []),
    `https://www.youtube.com/api/timedtext?v=${id}&lang=ko&kind=asr&fmt=json3`,
    `https://www.youtube.com/api/timedtext?v=${id}&lang=ko&fmt=json3`,
    `https://www.youtube.com/api/timedtext?v=${id}&lang=ko-KR&kind=asr&fmt=json3`,
  ];

  for (const sourceUrl of attempts) {
    try {
      const res = await fetch(sourceUrl, {
        headers: {
          "User-Agent":
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36",
          "Accept-Language": "ko-KR,ko;q=0.9",
          Referer: `https://www.youtube.com/watch?v=${id}`,
        },
        signal: AbortSignal.timeout(timeoutMs),
        cache: "no-store",
      });
      if (!res.ok) continue;
      const raw = await res.text();
      if (!raw || raw.length < 20) continue;
      const text = normalizePastedText(
        dedupeTranscriptRepeats(parseCaptionJson3(raw))
      );
      if (text.length >= 80 && looksLikeKoreanText(text)) {
        return { text, langTried: "ko-youtube", sourceUrl };
      }
    } catch {
      /* next */
    }
  }
  return null;
}
